#!/usr/bin/env python3
"""The requirement-to-test trace (QA-1): spec/requirements-trace.md, made from governance/requirements-trace.csv.

Usage: python3 scripts/generate-requirements-trace.py [--check] [repo-root]

The requirements are the `FR-n.m` of spec/06-functional-requirements.md, each with its words there. The CSV names, for
each, the tests (`path::test_name`, as in the hazard log) and in words what is not there. It fails when a requirement has
no row or a row no requirement, when a named test does not exist, or, with `--check`, when the page is stale. A
requirement with no test is shown, and is not a failure. A named test is not proof of the requirement.
"""
import csv
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("hazards", os.path.join(HERE, "check-hazard-log.py"))
hazards = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(hazards)

SPEC = os.path.join("spec", "06-functional-requirements.md")
DATA = os.path.join("governance", "requirements-trace.csv")
PAGE = os.path.join("spec", "requirements-trace.md")


def requirements(text):
    """Each `(id, words)` of the numbered sections, in order: from one id to the next, or the next heading."""
    body = text[text.index("### 6.1"):]
    out = []
    for section in re.split(r"^### .*$", body, flags=re.M):
        for m in re.finditer(r"(FR-\d+\.\d+)\s+(.*?)(?=FR-\d+\.\d+\s|\Z)", section, flags=re.S):
            words = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", " ".join(m.group(2).split())).strip()
            out.append((m.group(1), words))
    return out


def problems(reqs, rows, root):
    found = []
    ids, named = [i for i, _ in reqs], [r["id"] for r in rows]
    for what, these in (("the specification", ids), (DATA, named)):
        found += [f"{i} is in {what} twice" for i in sorted({i for i in these if these.count(i) > 1})]
    found += [f"{i} has no row in {DATA}" for i in ids if i not in named]
    found += [f"{i} is in {DATA} and not in {SPEC}" for i in named if i not in ids]
    for r in rows:
        for entry in hazards.split_evidence(r["tests"]):
            path, sep, name = entry.partition("::")
            if not sep or not name or not hazards.test_exists(root, path, name):
                found.append(f"{r['id']}: there is no test {entry}")
    return found


def cell(text):
    return text.replace("|", "\\|")


def page(reqs, rows):
    by = {r["id"]: r for r in rows}
    traced = [i for i, _ in reqs if by[i]["tests"].strip()]
    gaps = [i for i, _ in reqs if not by[i]["tests"].strip()]
    lines = [
        "# Requirements and their tests",
        "",
        "Generated by `scripts/generate-requirements-trace.py` from `governance/requirements-trace.csv` (QA-1); do not edit."
        " The requirements are those of [functional requirements](06-functional-requirements.md).",
        "",
        f"**{len(traced)} of {len(reqs)} name at least one test. {len(gaps)} name none:** {', '.join(gaps)}.",
        "",
        "A named test shows that something of the requirement is tested. It is not proof that the requirement is met, and"
        " the author chose the tests; no one has reviewed the choice. \"Lacks\" is in the author's words, and an empty one"
        " says only that nothing was written.",
        "",
        "| Id | Requirement | Tests | Lacks |",
        "|---|---|---|---|",
    ]
    for i, words in reqs:
        tests = hazards.split_evidence(by[i]["tests"])
        shown = "<br>".join(f"`{t.rpartition('/')[2]}`" for t in tests) or "**none**"
        lines.append(f"| {i} | {cell(words)} | {cell(shown)} | {cell(by[i]['lacks'])} |")
    return "\n".join(lines) + "\n"


def self_test():
    reqs = requirements("FR-9.9 above\n### 6.1 A\nFR-1.1 One\nline (part). FR-1.2 [Two](x.md) b.\n\n### 6.2 B\nFR-2.1\nC.\n")
    assert reqs == [("FR-1.1", "One line (part)."), ("FR-1.2", "Two b."), ("FR-2.1", "C.")], reqs
    rows = [{"id": "FR-1.1", "tests": "nowhere.rs::x", "lacks": ""}, {"id": "FR-3.3", "tests": "", "lacks": ""}]
    said = "\n".join(problems(reqs, rows, "."))
    for words in ("FR-1.2 has no row", "FR-3.3 is in", "FR-1.1: there is no test nowhere.rs::x"):
        assert words in said, said


def main(argv):
    self_test()
    args = argv[1:]
    check = "--check" in args
    root = next((a for a in args if not a.startswith("--")), ".")
    with open(os.path.join(root, SPEC), encoding="utf-8") as f:
        reqs = requirements(f.read())
    with open(os.path.join(root, DATA), newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    found = problems(reqs, rows, root)
    if not reqs:
        found.append(f"no requirement was read from {SPEC}; its format changed")
    for p in found:
        print(p, file=sys.stderr)
    if found:
        return 1
    text, path = page(reqs, rows), os.path.join(root, PAGE)
    if check:
        try:
            with open(path, encoding="utf-8") as f:
                fresh = f.read() == text
        except OSError:
            fresh = False
        if not fresh:
            print(f"{PAGE} is stale: run python3 scripts/generate-requirements-trace.py", file=sys.stderr)
            return 1
        print(f"{PAGE} is up to date")
        return 0
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
