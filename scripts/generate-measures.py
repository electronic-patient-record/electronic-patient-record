#!/usr/bin/env python3
"""The measures registry (SM-1, SM-2): spec/clinical-safety/measures.md, made from governance/clinical-safety/measures.csv.

Usage: python3 scripts/generate-measures.py [--check] [repo-root]

One row for each measure: what is counted, out of what, from where, who looks at it and how often, and the hazards it
serves. A source is `table:<name>`, and what is given today is `route:<path>` or `metric:<name>`; each must exist. It fails
on that, on a hazard that is not in the hazard log, on a measure with no numerator, denominator, owner, cadence or limits,
and, with `--check`, when the page is stale. A hazard with no measure is listed, and is not a failure. A measure sets no
hazard's status, and there is no threshold here.
"""
import csv
import os
import re
import sys

DATA = os.path.join("governance", "clinical-safety", "measures.csv")
LOG = os.path.join("governance", "clinical-safety", "hazard-log.csv")
PAGE = os.path.join("spec", "clinical-safety", "measures.md")
SERVICE = "electronic-patient-record-service-with-rust"
COLUMNS = ["id", "measure", "numerator", "denominator", "source", "computed", "owner", "cadence", "hazards", "limits"]
NEEDED = ["measure", "numerator", "denominator", "owner", "cadence", "limits"]


def split(cell):
    return [e.strip() for e in cell.split(";") if e.strip()]


def read(root, path):
    with open(os.path.join(root, path), newline="", encoding="utf-8") as f:
        return f.read()


def known(root):
    """What may be named: the tables of the schema map, the routes and the metrics."""
    return {
        "table": set(re.findall(r"^\| `(\w+)`", read(root, os.path.join("spec", "schema-map.md")), flags=re.M)),
        "route": set(re.findall(r'"(/api/[^"]+)"', read(root, os.path.join(SERVICE, "src", "routes.rs")))),
        "metric": set(re.findall(r'"(epr_\w+)"', read(root, os.path.join(SERVICE, "src", "metrics.rs")))),
    }


def problems(rows, header, hazard_ids, names):
    if header != COLUMNS:
        return [f"columns must be exactly: {','.join(COLUMNS)}"]
    found, seen = [], set()
    for r in rows:
        i = r["id"]
        if not re.fullmatch(r"M-\d{2}", i) or i in seen:
            found.append(f"{i!r} is not an id, or is there twice")
        seen.add(i)
        found += [f"{i}: no {c}" for c in NEEDED if not (r[c] or "").strip()]
        found += [f"{i}: there is no hazard {h}" for h in split(r["hazards"]) if h not in hazard_ids]
        for column, kinds in (("source", {"table"}), ("computed", {"route", "metric"})):
            for entry in split(r[column]):
                kind, _, name = entry.partition(":")
                if kind not in kinds or name not in names[kind]:
                    found.append(f"{i}: {column} names {entry}, which is not there")
    return found


def unmeasured(rows, hazards):
    served = {h for r in rows for h in split(r["hazards"])}
    return [(i, title) for i, title in hazards if i not in served]


def cell(text):
    return text.replace("|", "\\|")


def page(rows, hazards):
    missing = unmeasured(rows, hazards)
    given = [r["id"] for r in rows if r["computed"].strip()]
    out = [
        "# Safety measures",
        "",
        "Generated by `scripts/generate-measures.py` from `governance/clinical-safety/measures.csv` (SM-1, SM-2); do not edit."
        " Why, and what measuring cannot do: [measuring clinical safety](measurement.md).",
        "",
        "**A proposal. No Clinical Safety Officer has reviewed a measure or agreed a threshold, and there is none here. A"
        " measure sets no hazard's status.** The owners are roles and not people.",
        "",
        f"**{len(rows)} measures. {len(given)} have some figure that the service gives today ({', '.join(given)}), and none is"
        f" computed whole. {len(missing)} of {len(hazards)} hazards have no measure:** {', '.join(i for i, _ in missing)}.",
        "",
        "| Id | Measure | Counted | Out of | From | Given today | Owner | How often | Hazards | Limits |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        def names(column):
            return ", ".join(f"`{e.partition(':')[2]}`" for e in split(r[column])) or "nothing"
        out.append("| " + " | ".join([
            r["id"], cell(r["measure"]), cell(r["numerator"]), cell(r["denominator"]), names("source"), names("computed"),
            cell(r["owner"]), cell(r["cadence"]), ", ".join(split(r["hazards"])) or "none", cell(r["limits"])]) + " |")
    out += ["", "## Hazards with no measure", "", "| Hazard | |", "|---|---|"]
    out += [f"| {i} | {cell(title)} |" for i, title in missing]
    return "\n".join(out) + "\n"


def self_test():
    names = {"table": {"t"}, "route": {"/api/x"}, "metric": {"epr_y"}}
    good = dict(zip(COLUMNS, ["M-01", "m", "n", "d", "table:t", "route:/api/x; metric:epr_y", "o", "c", "H-001", "l"]))
    assert problems([good], COLUMNS, {"H-001"}, names) == []
    for column, value, words in (("source", "table:z", "which is not there"), ("source", "route:/api/x", "not there"),
                                 ("computed", "metric:z", "not there"), ("hazards", "H-9", "no hazard H-9"),
                                 ("limits", " ", "no limits"), ("id", "M-1", "not an id")):
        said = "\n".join(problems([{**good, column: value}], COLUMNS, {"H-001"}, names))
        assert words in said, (column, said)
    assert "twice" in "\n".join(problems([good, good], COLUMNS, {"H-001"}, names))
    assert unmeasured([good], [("H-001", "a"), ("H-002", "b")]) == [("H-002", "b")]


def main(argv):
    self_test()
    args = argv[1:]
    check = "--check" in args
    root = next((a for a in args if not a.startswith("--")), ".")
    reader = csv.DictReader(read(root, DATA).splitlines())
    rows = list(reader)
    hazards = [(h["id"], h["title"]) for h in csv.DictReader(read(root, LOG).splitlines())]
    found = problems(rows, reader.fieldnames, {i for i, _ in hazards}, known(root))
    for p in found:
        print(p, file=sys.stderr)
    if found:
        return 1
    text = page(rows, sorted(hazards))
    if check:
        try:
            fresh = read(root, PAGE) == text
        except OSError:
            fresh = False
        if not fresh:
            print(f"{PAGE} is stale: run python3 scripts/generate-measures.py", file=sys.stderr)
            return 1
        print(f"{PAGE} is up to date")
        return 0
    with open(os.path.join(root, PAGE), "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
